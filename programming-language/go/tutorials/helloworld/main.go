// `package main`은 Go 프로그램의 진입점을 정의하는 패키지이지만,
// 그외 파일에서는 해당 파일의 이름으로 작성하거나 디렉터리 이름으로 패키지를 정의해야 합니다.
package main

// `import` 문은 외부 패키지를 가져와서 사용할 수 있게 해주며, 여러 패키지를 한 번에 관리할 수 있도록 한다.
// 다만 사용하지 않는 패키지를 import하면 컴파일 에러가 발생하고, 대부분의 라이브러리는 URL을 통해 가져올 수 있다.
import "fmt"

// `main` 함수는 프로그램의 진입점으로, 프로그램 실행 시 가장 먼저 호출된다.
// `main.go` 파일 외에 `func main()` 함수를 사용하면 프로그램의 진입점으로 인식되지 않는다.
func main() {
	fmt.Println("Hello, World!")
}